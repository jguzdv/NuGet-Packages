namespace System.Linq;

/// <summary>
/// Specifies the strategy to use when enumerating child elements.
/// </summary>
public enum ChildEnumerationStrategy
{
    /// <summary>
    /// Enumerate child elements in breadth-first order.
    /// </summary>
    BreadthFirst,

    /// <summary>
    /// Enumerate child elements in depth-first order.
    /// </summary>
    DepthFirst
}

